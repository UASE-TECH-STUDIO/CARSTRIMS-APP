/**
 * Real, confirmed cause of iOS voice search silently doing nothing
 * (no permission popup, no entry in Settings, generic "hiccup" error
 * on tap): @capacitor-community/speech-recognition@7.0.1 ships no
 * Package.swift at all - it predates Capacitor 8's shift to Swift
 * Package Manager as the default, and was never migrated. This
 * project's iOS folder is 100% SPM (confirmed - no CocoaPods/Podfile
 * anywhere), so this plugin's native Swift implementation was never
 * actually being linked into the app at all - only its JS bridge
 * was. Every call into it (available(), requestPermissions(),
 * start()) had no real native code to reach, which is why iOS never
 * even got as far as asking for microphone/speech permission.
 *
 * node_modules is never committed to git (regenerated by every
 * fresh `npm install`, on Xcode Cloud and locally alike), so this
 * can't be fixed by hand-editing a file there once - it has to be
 * regenerated every time. Wired into package.json's "postinstall"
 * script so it runs automatically after every npm install,
 * regardless of environment (Xcode Cloud's ci_post_clone.sh, or
 * anyone running npm install locally to test).
 */
const fs = require("fs");
const path = require("path");

const pluginDir = path.join(__dirname, "..", "node_modules", "@capacitor-community", "speech-recognition");
const packageSwiftPath = path.join(pluginDir, "Package.swift");

if (!fs.existsSync(pluginDir)) {
  // Plugin isn't installed at all in this environment - nothing to patch.
  process.exit(0);
}

// Matches the source layout Capacitor's own plugins use, and the
// plugin's own actual source location confirmed from its podspec
// (s.source_files = 'ios/Plugin/**/*.{swift,h,m,c,cc,mm,cpp}') and
// its declared deployment target (s.ios.deployment_target = '14.0').
const packageSwiftContent = `// swift-tools-version: 5.9
import PackageDescription

let package = Package(
    name: "CapacitorCommunitySpeechRecognition",
    platforms: [.iOS(.v14)],
    products: [
        .library(
            name: "CapacitorCommunitySpeechRecognition",
            targets: ["CapacitorCommunitySpeechRecognitionPlugin"])
    ],
    dependencies: [
        .package(url: "https://github.com/ionic-team/capacitor-swift-pm.git", from: "7.0.0")
    ],
    targets: [
        .target(
            name: "CapacitorCommunitySpeechRecognitionPlugin",
            dependencies: [
                .product(name: "Capacitor", package: "capacitor-swift-pm"),
                .product(name: "Cordova", package: "capacitor-swift-pm")
            ],
            path: "ios/Plugin")
    ]
)
`;

fs.writeFileSync(packageSwiftPath, packageSwiftContent, "utf8");
console.log("[patch-speech-recognition-spm] Wrote Package.swift for @capacitor-community/speech-recognition (missing from the published package, needed for this project's SPM-only iOS build).");
